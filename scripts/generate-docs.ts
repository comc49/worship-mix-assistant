/**
 * Regenerates the review docs from the data, so the docs cannot drift from the code.
 * Also checks that every verified quote really appears on its cited page of the manual,
 * when the manuals are present in docs/manuals/.
 */

const MANUAL_FILES: Record<string, string> = {
  x32: 'docs/manuals/x32-user-manual.pdf',
  wingCompact: 'docs/manuals/wing-series-user-manual.pdf',
};

function normalize(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/[’‘]/g, "'").trim().toLowerCase();
}

function readManualPages(pdfPath: string): string[] | null {
  if (!existsSync(pdfPath)) {
    return null;
  }
  const text = execFileSync('pdftotext', ['-layout', pdfPath, '-'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return text.split('\f').map(normalize);
}

function cell(value: unknown): string {
  const text = typeof value === 'string' ? value : JSON.stringify(value);
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function writeConsoleSources(): number {
  const lines: string[] = ['# Console sources', '', 'Generated by `npm run docs` from the console profiles. Do not edit by hand.', ''];
  lines.push('Every fact in a console profile is listed with the manual passage it was read from, or marked **UNVERIFIED**.', '');
  let quoteProblems = 0;

  for (const profile of Object.values(CONSOLE_PROFILES) as ConsoleProfile[]) {
    const pages = readManualPages(MANUAL_FILES[profile.id]);
    lines.push(`## ${profile.name}`, '', `Manual: ${profile.manualTitle}`, '');
    if (pages === null) {
      lines.push('_The manual PDF was not present when this file was generated, so quotes were not re-checked._', '');
    }
    lines.push('| Fact | Value | Source | Quote / note |', '| --- | --- | --- | --- |');

    const unverified: string[] = [];
    for (const [key, fact] of Object.entries(profile.facts) as [string, Fact<unknown>][]) {
      const source = fact.source;
      if (source.status === 'unverified') {
        unverified.push(`- **${key}**: ${source.note}`);
        lines.push(`| ${key} | ${cell(fact.value)} | **UNVERIFIED** | ${cell(source.note)} |`);
        continue;
      }
      let check = '';
      if (pages !== null) {
        const quote = normalize(source.quote);
        const onPage = source.page !== null && pages[source.page - 1] !== undefined && pages[source.page - 1].includes(quote);
        const anywhere = pages.findIndex((page) => page.includes(quote));
        if (onPage) {
          check = ' ✓';
        } else if (anywhere !== -1) {
          check = ` (quote found on p${anywhere + 1})`;
          quoteProblems = quoteProblems + 1;
        } else {
          check = ' **QUOTE NOT FOUND**';
          quoteProblems = quoteProblems + 1;
        }
      }
      const note = source.note.length > 0 ? ` ${source.note}` : '';
      lines.push(`| ${key} | ${cell(fact.value)} | ${cell(source.section)}, p${source.page ?? '?'}${check} | "${cell(source.quote)}"${cell(note)} |`);
    }
    lines.push('', `### Still UNVERIFIED on the ${profile.name}`, '', ...unverified, '');
  }
  writeFileSync('docs/console-sources.md', lines.join('\n'));
  return quoteProblems;
}

function writeKnowledgeReview(): void {
  const lines: string[] = ['# Knowledge review', '', 'Generated by `npm run docs` from `src/app/core/knowledge`. Do not edit by hand: change the data and regenerate.', ''];

  lines.push('## The ten values I am least sure of', '');
  lines.push(
    '1. **Live-room low cut bump (+20 Hz on everything except kick and bass)** plus **+10 Hz for HVAC on open mics.** Stacked, a medium voice lands at 130 Hz and a low voice sits exactly on its 110 Hz limit.',
    '2. **Vocal low-cut ceilings by voice range** (110 / 140 / 170 Hz). These decide when stacking stops; they are judgment calls.',
    '3. **Wedge cap of 6 dB vocal gain reduction with no makeup gain.** From the brief; the right number depends on how loud your wedges run.',
    '4. **Beginner electric guitar: ratio +6 (to 8:1) with a 5 ms attack.** "Limiter-style" as asked, but it is the most aggressive setting in the app.',
    '5. **Keys low cut stack:** 60 Hz baseline, +30 beginner (bass present), +20 live room, +20 because a bass guitar is in the band = 130 Hz. Limit is 150 Hz.',
    '6. **Electronic drums as a stereo pair: 2 dB of compression, capped at 3 dB.** Many engineers would use none.',
    '7. **Reverb times:** plate 1.6 s, hall 2.2 s, drum room 0.8 s; live room shortens them to 1.2 / 1.6 / 0.6 s and caps the sends.',
    '8. **Energy DCA members** (electronic drums, snare, toms, hi-hat, overheads, electric guitar) and **Low End DCA members** (kick, bass guitar, synth bass, cajon). Assumed: the brief left these brackets unfilled.',
    '9. **Monitor starting levels** (own channel 0 dB, lead vocal -6 dB to everyone, keys -10 dB, electronic drums -8 dB) and which musicians share a mix.',
    '10. **No gate on the snare.** The conservative choice; a gate is offered only under "if you hear".',
    '',
  );

  lines.push('## Instrument baselines', '');
  for (const profile of INSTRUMENT_PROFILES) {
    lines.push(`### ${profile.label} (\`${profile.id}\`)`, '', `Connections: ${profile.connections.join(', ')}. DCAs: ${profile.dcas.join(', ') || 'none'}. Group bus: ${profile.groupBus ?? 'none'}. Sub send (own-bus sub): ${profile.sendToSubBus ? 'yes' : 'no'}.`, '');
    lines.push('| Setting | Default | Usable range | Musical limit | Why |', '| --- | --- | --- | --- | --- |');
    for (const [key, value] of Object.entries(profile.params)) {
      const explicit = EXPLICIT_LIMITS[profile.id]?.[key as keyof (typeof EXPLICIT_LIMITS)[string]];
      const limit = explicit === undefined ? 'usable range' : `${explicit.floor} to ${explicit.ceiling} (${explicit.why})`;
      lines.push(`| ${key} | ${value.value} ${value.unit} | ${value.min} to ${value.max} | ${cell(limit)} | ${cell(value.why)} |`);
    }
    lines.push('', `Gate: ${profile.gateThreshold === null ? `none. ${profile.noGateWhy}` : profile.gateThreshold.value}`);
    lines.push('', `Compressor: ${profile.makeupGain === null ? `none. ${profile.noCompressorWhy}` : 'yes, set by target gain reduction (never a threshold in dB)'}`);
    if (profile.suggestedCuts.length > 0) {
      lines.push('', 'Optional suggested cuts:');
      profile.suggestedCuts.forEach((cut) => lines.push(`- ${cut.label}: ${cut.gainDb} dB at ${cut.frequencyHz} Hz, ${cut.q} Q. ${cut.why}`));
    }
    lines.push('', 'If you hear:');
    profile.ifYouHear.forEach((entry) => lines.push(`- ${entry.hear}: ${entry.tryThis}`));
    lines.push('');
  }

  lines.push('## Vocal low cut by voice range', '', '| Voice | Low cut | Floor | Ceiling | Optional mud cut | Why |', '| --- | --- | --- | --- | --- | --- |');
  VOCAL_LOW_CUT_BY_RANGE.forEach((entry) => lines.push(`| ${entry.voiceRange} | ${entry.baselineHz} Hz | ${entry.floor} Hz | ${entry.ceiling} Hz | ${entry.suggestedMudCutHz} Hz | ${cell(entry.why)} |`));
  lines.push('', '## Mic models', '', '| Mic | Low cut offset | Wedge note | Why |', '| --- | --- | --- | --- |');
  MIC_MODELS.forEach((mic) => lines.push(`| ${mic.label} | ${mic.lowCutOffsetHz} Hz | ${cell(mic.wedgeNote)} | ${cell(mic.why)} |`));

  lines.push('', '## Skill modifiers', '', 'Intermediate is the baseline. Skill never chooses tonal EQ.', '', '| Role | Level | Changes | Why | Coaching note |', '| --- | --- | --- | --- | --- |');
  for (const modifier of SKILL_MODIFIERS) {
    const changes = modifier.adjustments
      .map((adjustment) => {
        const only = adjustment.onlyProfileIds.length > 0 ? ` [only ${adjustment.onlyProfileIds.join(', ')}]` : '';
        const requires = adjustment.requiresRolesInBand.length > 0 ? ` [only with ${adjustment.requiresRolesInBand.join(', ')} in the band]` : '';
        return `${adjustment.param} ${adjustment.amount >= 0 ? '+' : ''}${adjustment.amount}${only}${requires}`;
      })
      .join('; ');
    lines.push(`| ${modifier.role} | ${modifier.level} | ${cell(changes || 'none')} | ${cell(modifier.why)} | ${cell(modifier.coaching)} |`);
  }
  lines.push('', '### Behavior descriptions shown instead of skill labels', '', '| Role | Lowest | Middle | Highest |', '| --- | --- | --- | --- |');
  SKILL_DESCRIPTIONS.forEach((entry) => lines.push(`| ${entry.role} | ${entry.beginner} | ${entry.intermediate} | ${entry.advanced} |`));

  lines.push('', '## Room modifiers', '');
  for (const set of ROOM_MODIFIERS) {
    lines.push(`### ${set.reverberance} room`, '', set.summary, '', '| Role | Changes | Why |', '| --- | --- | --- |');
    for (const [role, modifier] of Object.entries(set.byRole)) {
      const changes = modifier.adjustments.map((adjustment) => `${adjustment.param} ${adjustment.kind === 'add' ? (adjustment.amount >= 0 ? '+' : '') + adjustment.amount : `${adjustment.kind} ${adjustment.amount}`}`).join('; ');
      lines.push(`| ${role} | ${cell(changes)} | ${cell(modifier.why)} |`);
    }
    lines.push('', 'Effect times:');
    for (const [effect, time] of Object.entries(set.effectTime)) {
      lines.push(`- ${effect}: ${time.addSeconds >= 0 ? '+' : ''}${time.addSeconds} s${time.ceilingSeconds === null ? '' : `, never above ${time.ceilingSeconds} s`}. ${time.why}`);
    }
    lines.push('');
  }
  lines.push('Constant low-frequency noise (HVAC): +10 Hz low cut on every open mic except kick and cajon.', '');
  lines.push('Precedence: offsets add in order (mic, player, room, band), then context limits clamp (room reverb ceilings, wedge cap), then the musical limit clamps last.', '');

  lines.push('## Send effects', '', '| Priority | Effect | Time | Limit | Why |', '| --- | --- | --- | --- | --- |');
  SEND_EFFECTS.forEach((effect) => lines.push(`| ${effect.priority} | ${effect.label} | ${effect.time === null ? cell(effect.timeNote) : `${effect.time.value} s (${effect.time.min} to ${effect.time.max})`} | ${effect.timeLimit === null ? '-' : `${effect.timeLimit.floor} to ${effect.timeLimit.ceiling} s`} | ${cell(effect.why)} |`));

  lines.push('', '## Ensemble rules', '', '| Rule | Fires when the band has | Arrangement advice (always first) | Changes | Why |', '| --- | --- | --- | --- | --- |');
  for (const rule of ENSEMBLE_RULES) {
    const when = rule.requiresOneOfEach.map((oneOf) => oneOf.join(' or ')).join(' AND ');
    const changes = rule.adjustments.map((entry) => `${entry.targetRoles.join(', ')}: ${entry.adjustment.param} ${entry.adjustment.amount >= 0 ? '+' : ''}${entry.adjustment.amount}`).join('; ');
    const sub = rule.removeSubSendFrom.length > 0 ? ` No sub send for ${rule.removeSubSendFrom.join(', ')}.` : '';
    lines.push(`| ${rule.title} | ${cell(when)} | ${cell(rule.arrangementAdvice)} | ${cell((changes || 'none') + sub)} | ${cell(rule.why)} |`);
  }
  lines.push('');
  writeFileSync('docs/knowledge-review.md', lines.join('\n'));
}

const quoteProblems = writeConsoleSources();
writeKnowledgeReview();
writeTroubleshootingReview();
console.log(`docs written. Quotes not on their cited page: ${quoteProblems}`);
