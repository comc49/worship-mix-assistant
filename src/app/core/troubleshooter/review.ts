import { SYMPTOM_GROUPS, TROUBLESHOOTING_TREES } from '../knowledge/troubleshooting';
import { StepSafety, TroubleshootingNode, TroubleshootingTree } from '../knowledge/troubleshooting/types';
import { describeCondition } from './conditions';
import { TroubleshootContext } from './context';
import { DEFERRED_FIX_TEXT } from './resolver';
import { resolveText } from './tokens';

/**
 * Builds docs/troubleshooting-review.md: every tree, every node, in plain language.
 * Unlike the screen, the review lists ALL nodes (also the ones a given room or situation hides),
 * with the conditions written out, so the whole tree can be checked on paper.
 * The text is resolved for the context passed in (the script uses the placeholder fixture band).
 */

function safetyLabel(safety: StepSafety): string {
  if (safety === 'rehearsalOnly') {
    return 'REHEARSAL ONLY';
  }
  return 'safe during a service';
}

/** Numbers the nodes in the order they are written in the data file, so "go to 4" is readable. */
function numberNodes(tree: TroubleshootingTree): Record<string, number> {
  const numbers: Record<string, number> = {};
  const nodeIds = Object.keys(tree.nodes);
  nodeIds.forEach((nodeId, index) => {
    numbers[nodeId] = index + 1;
  });
  return numbers;
}

function describeNode(nodeId: string, node: TroubleshootingNode, numbers: Record<string, number>, context: TroubleshootContext): string[] {
  const lines: string[] = [];
  const stepNumber = numbers[nodeId];
  const goTo = (targetId: string): string => `step ${numbers[targetId]}`;

  if (node.kind === 'check') {
    lines.push(`**${stepNumber}. Check** (${safetyLabel(node.safety)})`);
  } else if (node.kind === 'fix') {
    lines.push(`**${stepNumber}. Fix** (${safetyLabel(node.safety)})`);
  } else {
    lines.push(`**${stepNumber}. Ask for help** (${safetyLabel(node.safety)})`);
  }
  lines.push('');

  if (node.when !== undefined) {
    lines.push(`- Only when ${describeCondition(node.when.condition)}. Otherwise go to ${goTo(node.when.otherwise)}.`);
  }

  if (node.kind === 'check') {
    lines.push(`- Do${node.looksOnly === true ? ' (look only)' : ''}: ${resolveText(node.action, context).text}`);
    lines.push(`- Ask: ${resolveText(node.question, context).text}`);
    lines.push(`- Yes: go to ${goTo(node.yes)}. No: go to ${goTo(node.no)}.`);
    if (node.safety === 'rehearsalOnly') {
      lines.push(`- During a service this check is skipped: go to ${goTo(node.duringService ?? node.no)}.`);
    }
  }

  if (node.kind === 'fix') {
    if (typeof node.arrangementAdvice === 'string') {
      lines.push(`- With the band first: ${resolveText(node.arrangementAdvice, context).text}`);
    }
    if (Array.isArray(node.arrangementAdvice)) {
      for (const adviceLine of node.arrangementAdvice) {
        const condition = adviceLine.when === undefined ? '' : ` (only when ${describeCondition(adviceLine.when)})`;
        lines.push(`- With the band first${condition}: ${resolveText(adviceLine.text, context).text}`);
      }
    }
    lines.push(`- Then: ${resolveText(node.text, context).text}`);
    if (node.controlRefs.length > 0) {
      lines.push(`- Console facts listed with the fix: ${node.controlRefs.join(', ')}`);
    }
    if (node.safety === 'rehearsalOnly' && node.duringService !== undefined) {
      lines.push(`- During a service, shown instead: ${goTo(node.duringService)}.`);
    }
    if (node.safety === 'rehearsalOnly' && node.duringService === undefined) {
      lines.push(`- During a service, shown instead: "${DEFERRED_FIX_TEXT}"`);
    }
  }

  if (node.kind === 'askForHelp') {
    lines.push(`- ${resolveText(node.text, context).text}`);
  }

  lines.push('');
  return lines;
}

export function buildTroubleshootingReviewMarkdown(context: TroubleshootContext): string {
  const lines: string[] = [
    '# Troubleshooting review',
    '',
    'Generated by `npm run docs` from `src/app/core/knowledge/troubleshooting`. Do not edit by hand: change the data and regenerate.',
    '',
    `Names, values and control names below are filled in for the placeholder test band in "${context.room.name}" on the ${context.profile.name}. The app fills them in for the current band, room and console.`,
    '',
    'Every step is one action and one question. Steps marked REHEARSAL ONLY are hidden while the app is set to "Service". Values are typical starting points; ears decide.',
    '',
  ];

  for (const group of SYMPTOM_GROUPS) {
    lines.push(`## ${group.title}`, '');
    const treesInGroup = TROUBLESHOOTING_TREES.filter((tree) => tree.group === group.id);
    for (const tree of treesInGroup) {
      const numbers = numberNodes(tree);
      lines.push(`### ${tree.symptom}`, '');
      if (tree.needsOneOfEach.length > 0) {
        const needs = tree.needsOneOfEach.map((roles) => roles.join(' or ')).join(', and ');
        lines.push(`Only offered when the band has: ${needs}.`, '');
      }
      lines.push(`Starts at step ${numbers[tree.entryNodeId]}.`, '');
      for (const [nodeId, node] of Object.entries(tree.nodes)) {
        lines.push(...describeNode(nodeId, node, numbers, context));
      }
    }
  }

  return lines.join('\n');
}
